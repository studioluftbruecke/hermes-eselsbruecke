// Build the Desktop half (PLAN constraint 9): bundle desktop/src/index.js with the pinned packages into
// desktop/plugin.js, write the o200k ranks to data/o200k_base.json and the licences of everything bundled
// to THIRD_PARTY_NOTICES.md (X19), apply the three literal rewrites on the output (P4, P12), then check
// what can be checked in node:
//   - the runtime loader's import scan, lifted from the installed Desktop source (P11 method): Hermes'
//     source tree comes from HERMES_SOURCE, and a missing runtime-loader.ts fails the build (X20);
//   - the 16 MB plugin.js cap (apps/desktop/electron/main.ts PLUGIN_SOURCE_MAX_BYTES);
//   - module evaluation CPU (budget 100 ms on the ARM build box, constraint 20), with stand-ins for the SDK and
//     React, string code generation disabled as in the renderer.
// Hermes' admission lint and install scan are Python; tests/test_desktop_build.py runs them.
//
// Usage (from plugins/eselsbruecke/desktop/build, after `npm ci`; HERMES_SOURCE is Hermes' source tree,
// the folder that holds hermes_cli/ and apps/desktop/):
//   HERMES_SOURCE=... node build.mjs                 build and check; prints one JSON line
//   HERMES_SOURCE=... node build.mjs --check-only    check the committed files without rebuilding
//   HERMES_SOURCE=... node build.mjs --out DIR       build into DIR (plugin.js, o200k_base.json,
//                                                    THIRD_PARTY_NOTICES.md) and check those; the test
//                                                    compares their SHA-256 with the committed files
import crypto from 'crypto'
import fs from 'fs'
import { createRequire } from 'module'
import path from 'path'
import { fileURLToPath, pathToFileURL } from 'url'

const here = path.dirname(fileURLToPath(import.meta.url))
const desktop = path.resolve(here, '..')
const plugin = path.resolve(desktop, '..')
const argOut = process.argv.indexOf('--out')
const outDir = argOut > 0 ? path.resolve(process.argv[argOut + 1]) : null
if (outDir) fs.mkdirSync(outDir, { recursive: true })
const outfile = outDir ? path.join(outDir, 'plugin.js') : path.join(desktop, 'plugin.js')
const ranksFile = outDir ? path.join(outDir, 'o200k_base.json') : path.join(plugin, 'data', 'o200k_base.json')
const noticesFile = outDir ? path.join(outDir, 'THIRD_PARTY_NOTICES.md') : path.join(plugin, 'THIRD_PARTY_NOTICES.md')
const require = createRequire(path.join(here, 'package.json'))
const checkOnly = process.argv.includes('--check-only')
const MAX_BYTES = 16 * 1024 * 1024
const EVAL_BUDGET_MS = 100

// Every package esbuild puts into plugin.js (X19), with where its licence text comes from: the package's
// own file in node_modules, or desktop/build/licenses/ for the two packages that ship none.
const pkgJson = name => JSON.parse(fs.readFileSync(path.join(here, 'node_modules', name, 'package.json'), 'utf8'))
const BUNDLED = [
  { name: 'prettier', use: 'the formatter (Markdown, TypeScript, JavaScript, CSS, HTML, YAML)', licence: 'node_modules/prettier/LICENSE' },
  { name: 'qrcode-generator', use: 'the QR code tool', licence: 'licenses/qrcode-generator.LICENSE', repo: 'https://github.com/kazuhikoarase/qrcode-generator' },
  { name: 'js-tiktoken', use: 'the exact token count (lite build)', licence: 'licenses/js-tiktoken.LICENSE', repo: 'https://github.com/dqbd/tiktoken' },
  { name: 'base64-js', use: 'a dependency of js-tiktoken', licence: 'node_modules/base64-js/LICENSE' },
].map(p => ({ ...p, version: pkgJson(p.name).version, licenseId: pkgJson(p.name).license }))
const ESBUILD = { name: 'esbuild', version: pkgJson('esbuild').version, licence: 'node_modules/esbuild/LICENSE.md' }
const EFF_WORDLIST = path.join(plugin, 'data', 'eff_short_wordlist_1.txt')

