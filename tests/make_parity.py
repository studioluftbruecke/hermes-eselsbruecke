"""Write tests/fixtures/parity.json from the Python engines (run once, then review the diff).

The fixture is the contract the Desktop half's JavaScript must meet (tests/test_desktop_parity.mjs);
known reference values are asserted separately in tests/test_convert.py, so a wrong engine cannot
silently write a wrong fixture.

    python3 tests/make_parity.py     (from the plugin folder, with the test environment's packages)
"""
import datetime as dt
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("esb_parity", ROOT / "__init__.py", submodule_search_locations=[str(ROOT)])
mod = importlib.util.module_from_spec(spec)
sys.modules["esb_parity"] = mod
spec.loader.exec_module(mod)
import importlib  # noqa: E402

conv = importlib.import_module("esb_parity.engines.convert")
text = importlib.import_module("esb_parity.engines.text")
timers = importlib.import_module("esb_parity.timers")

ENC = ["hello", "Grüße aus Berlin", "a+b=c & d/e?f", "emoji 🎉 ok", "", "line\nbreak", "~!*()'"]
COLOURS = [("#2f9e6b", "#ffffff"), ("#ff0000", "#000000"), ("#ffffff", "#000000"), ("#777", "#fff"),
           ("rgb(47 158 107)", None), ("hsl(153 54% 40%)", None), ("oklch(62.8% 0.258 29.2)", None),
           ("#2f9e6b80", None), ("rgba(0, 0, 255, 0.5)", "#ffffff"), ("oklch(90% 0.4 140)", None)]
TIMES = [("2026-11-09 10:00", "Europe/Berlin", ["UTC", "America/New_York", "Asia/Tokyo", "Asia/Kolkata"]),
         ("2026-03-29 01:30", "Europe/Berlin", ["UTC"]), ("2026-07-01 23:45", "America/Los_Angeles", ["Europe/Berlin"])]
STAMPS = [("1794245079", ["UTC", "Europe/Berlin"]), ("1794245079976", ["UTC"]), ("0", ["UTC"]),
          ("2026-11-09T10:00:00+01:00", ["UTC"])]
T0 = dt.datetime(2026, 11, 9, 10, 0, tzinfo=dt.timezone(dt.timedelta(hours=1)))
_PLAN = timers.pomodoro_plan()
TIMERS = [  # (timer record, the instants asked, the window for due events)
    ({"id": "t1", "kind": "pomodoro", "plan": _PLAN, "started": timers.iso(T0), "paused": []}, [0, 24.5, 26, 121, 200], (24, 31)),
    ({"id": "t2", "kind": "pomodoro", "plan": _PLAN, "started": timers.iso(T0),
      "paused": [[timers.iso(T0 + dt.timedelta(minutes=10)), timers.iso(T0 + dt.timedelta(minutes=15))]]}, [26, 31], (24, 31)),
    ({"id": "t3", "kind": "pomodoro", "plan": _PLAN, "started": timers.iso(T0),
      "paused": [[timers.iso(T0 + dt.timedelta(minutes=10)), None]]}, [60], (0, 60)),
    ({"id": "c1", "kind": "countdown", "plan": [{"phase": "countdown", "minutes": 2}], "started": timers.iso(T0),
      "paused": [], "label": "tea"}, [1, 3], (1, 3)),
]
_KEEP = ("index", "phase", "remaining_s", "remaining_min", "ends_at", "paused", "done", "elapsed_s")


def _timer_case(t, minutes, window):
    at = lambda m: T0 + dt.timedelta(minutes=m)  # noqa: E731
    states = []
    for m in minutes:
        s = timers.phase_at(t, at(m))
        states.append({"at": timers.iso(at(m)), **{k: s[k] for k in _KEEP}})
    due = timers.due_events(t, at(window[0]), at(window[1]))
    return {"timer": t, "states": states, "due": {"since": timers.iso(at(window[0])), "now": timers.iso(at(window[1])),
                                                    "keys": [e["key"] for e in due], "at": [e["at"] for e in due]}}


COUNTS = ["hello world", "Heute muss ich noch zwei Features fixen und Mama anrufen.", "日本語のテキスト", "",
          '{"a": [1, 2, 3]}']

out = {
    "_comment": "Generated by tests/make_parity.py from the Python engines; the Desktop half must equal it.",
    "encode": [{"text": t, "scheme": s, "encoded": conv.encode(t, s)} for t in ENC for s in conv.SCHEMES],
    "colour": [{"input": c, "background": b, "out": conv.colour(c, b)} for c, b in COLOURS],
    "time": [{"time": t, "from": f, "to": z, "out": conv.convert_time(t, f, z)} for t, f, z in TIMES],
    "timestamp": [{"value": v, "zones": z, "out": conv.convert_timestamp(v, z)} for v, z in STAMPS],
    "count": [{"text": t, "out": text.count(t)} for t in COUNTS],
    "timer": [_timer_case(t, m, w) for t, m, w in TIMERS],
    "uuid": {"v4": r"^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$",
             "v7": r"^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$"},
}
for row in out["count"]:
    row["out"].pop("tokens_label", None)
path = ROOT / "tests" / "fixtures" / "parity.json"
path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print("wrote", path, len(out["encode"]), "encode,", len(out["colour"]), "colour,", len(out["time"]), "time rows")
